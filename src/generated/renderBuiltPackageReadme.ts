import type {GameBlueprintManifest} from "./GameBlueprint.js";

// A short orientation doc dropped at the root of every "pokie build" package, so the output is
// understandable on its own — without reading GamePackageGenerator or this repository's docs.
export function renderBuiltPackageReadme(manifest: GameBlueprintManifest, usesLocalRuntime = false): string {
    return `# ${manifest.name}

Generated by \`pokie build\` from a \`GameBlueprint\` JSON config. This package is playable as-is —
no build step — through the standard POKIE game package contract, once its runtime dependency is available.
${usesLocalRuntime
        ? "This build links the POKIE installation that created it and declares that same installation as a `file:` dependency in `package.json` and `package-lock.json`. A later `npm install` keeps using it, including for an unpublished candidate."
        : "This library-generated package declares a POKIE version range. Install that version from an available registry or explicitly select your local POKIE installation before use."}
Run \`npm install && npm run build\` to compile \`src/index.ts\` yourself rather than use the
\`dist/index.js\` already sitting in this package.

## Structure

- \`package.json\` — name/version/description from the blueprint's \`manifest\`, a \`@fromstan/pokie\` dependency,
  and \`start\`/\`server\`/\`client\`/\`build\` scripts. \`pokie.entry\`/\`main\`/\`exports\` all point at
  \`dist/index.js\`, the same entry path \`pokie create\`/\`pokie init\` packages compile their own
  TypeScript source into.
- \`node_modules/@fromstan/pokie\` — when built with a local runtime, a link to that installation for
  immediate execution. This dependency directory is not a published package file.
- \`package-lock.json\`/\`tsconfig.json\` — the same lockfile seed/compiler config \`pokie create\`/
  \`pokie init\` write, so \`npm install && npm run build\` behaves identically here.
- \`src/index.ts\`/\`dist/index.js\` — the \`PokieGame\` implementation: a \`VideoSlotConfig\` assembled
  from the blueprint (reels, symbols, paytable, paylines, reel strips/weights), wrapped in a
  \`VideoSlotSession\`. Both files hold the exact same generated logic — \`dist/index.js\` is written
  directly (not compiled from \`src/index.ts\`), so this package is playable immediately with no
  \`npm install\`/\`npm run build\` step; \`src/index.ts\` exists so a real \`npm run build\` (if you ever
  run one) reproduces an equivalent \`dist/index.js\`, rather than nothing at all.

**Do not hand-edit \`src/index.ts\` or \`dist/index.js\`** — re-run \`pokie build <config.json> --target tsPackage --out <new-directory>\`
to regenerate this package after changing the blueprint. \`pokie build\` only ever writes into a
missing or empty directory — there is no in-place merge/rebuild, so choose a new \`--out\` directory
for the next build. Keep the original Blueprint for design changes.

## Developer workflow

A local \`file:\` dependency requires the original POKIE installation to remain at its recorded location.
When moving to another machine, explicitly select an available runtime with
\`npm install /absolute/path/to/fromstan-pokie.tgz\` (the same candidate archive), or
\`npm install /absolute/path/to/installed/pokie\`, then run \`npm install\` for the remaining developer
dependencies. A published compatible version may also be selected explicitly when available.
No registry publication of this candidate is assumed. On the original machine:

\`\`\`
npm install

npx --no-install pokie inspect .
npx --no-install pokie validate .
npx --no-install pokie sim . --rounds 10000 --seed demo --out sim.json
npx --no-install pokie report sim.json
npx --no-install pokie replay . --seed demo --round 1
npx --no-install pokie dev .
\`\`\`

See [\`pokie\`'s CLI docs](https://github.com/fromstan/pokie/blob/develop/docs/cli.md) for what each
command does and every available option.
`;
}
