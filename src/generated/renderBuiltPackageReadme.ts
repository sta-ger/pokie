import type {GameBlueprintManifest} from "./GameBlueprint.js";

// A short orientation doc dropped at the root of every "pokie build" package, so the output is
// understandable on its own — without reading GamePackageGenerator or this repository's docs.
export function renderBuiltPackageReadme(manifest: GameBlueprintManifest): string {
    return `# ${manifest.name}

Generated by \`pokie build\` from a \`GameBlueprint\` JSON config. This package is playable as-is —
no build step — through the standard POKIE game package contract, and carries the exact same file
set \`pokie create\`/\`pokie init\` packages do, for the same reason: \`npm install && npm run build\`
still works here too, if you'd rather compile \`src/index.ts\` yourself than trust the \`dist/index.js\`
already sitting in this package.

## Structure

- \`package.json\` — name/version/description from the blueprint's \`manifest\`, a \`pokie\` dependency,
  and \`start\`/\`server\`/\`client\`/\`build\` scripts. \`pokie.entry\`/\`main\`/\`exports\` all point at
  \`dist/index.js\`, the same entry path \`pokie create\`/\`pokie init\` packages compile their own
  TypeScript source into.
- \`package-lock.json\`/\`tsconfig.json\` — the same lockfile seed/compiler config \`pokie create\`/
  \`pokie init\` write, so \`npm install && npm run build\` behaves identically here.
- \`src/index.ts\`/\`dist/index.js\` — the \`PokieGame\` implementation: a \`VideoSlotConfig\` assembled
  from the blueprint (reels, symbols, paytable, paylines, reel strips/weights), wrapped in a
  \`VideoSlotSession\`. Both files hold the exact same generated logic — \`dist/index.js\` is written
  directly (not compiled from \`src/index.ts\`), so this package is playable immediately with no
  \`npm install\`/\`npm run build\` step; \`src/index.ts\` exists so a real \`npm run build\` (if you ever
  run one) reproduces an equivalent \`dist/index.js\`, rather than nothing at all.

**Do not hand-edit \`src/index.ts\` or \`dist/index.js\`** — re-run \`pokie build <config.json> --out .\`
to regenerate this package after changing the blueprint. \`pokie build\` only ever writes into a
missing or empty directory — there is no in-place merge/rebuild, so overwriting this package means
removing it (or its contents) first, or building into a different \`--out\` directory.

## Workflow

\`\`\`
npm install

npx pokie inspect .
npx pokie validate .
npx pokie sim . --rounds 10000 --seed demo --out sim.json
npx pokie report sim.json
npx pokie replay . --seed demo --round 1
npx pokie dev .
\`\`\`

See [\`pokie\`'s CLI docs](https://github.com/sta-ger/pokie/blob/master/docs/cli.md) for what each
command does and every available option.
`;
}
