import crypto from "crypto";
import fs from "fs";
import path from "path";
import {buildGameBuildInfo, GENERATED_PACKAGE_FILES} from "./buildGameBuildInfo.js";
import type {GameBlueprint} from "./GameBlueprint.js";
import type {GameBuildInfo} from "./GameBuildInfo.js";
import type {GameBuildInfoReelStripGeneration} from "./GameBuildInfoReelStripGeneration.js";
import type {GamePackageGenerating} from "./GamePackageGenerating.js";
import type {GeneratedGamePackage} from "./GeneratedGamePackage.js";
import {materializeReelStrips} from "./materializeReelStrips.js";
import {renderGeneratedGameModule} from "./renderGeneratedGameModule.js";
import {renderGeneratedPackageReadme} from "./renderGeneratedPackageReadme.js";
import {resolveReelStripGeneration} from "./resolveReelStripGeneration.js";

const DEFAULT_DESCRIPTION = 'Generated by "pokie build" — a POKIE video slot game package.';
const BUILD_INFO_RELATIVE_PATH = "src/generated/build-info.json";

// Where every generated file's actual content lives -- a directory this generator exclusively owns
// (never node_modules, never anything a user or "npm install" might put at projectRoot). Each rebuild's
// content lands in its own freshly named generation subdirectory here (GENERATION_DIR_PREFIX-<random>),
// and LIVE_DIR_NAME is never one of those directories itself -- it's a *symlink* pointing at whichever
// generation directory is currently published. Swapping which generation is live is therefore a single
// symlink-over-symlink rename (see publishLiveGeneration), never a rename of real content: the previous
// generation directory is left completely untouched on disk until after that swap has already succeeded.
// See publishGeneratedFiles for how the four public paths (package.json, README.md,
// src/generated/index.js, src/generated/build-info.json) get to this content without ever being
// rewritten themselves on an ordinary rebuild.
const GENERATIONS_DIR_NAME = ".pokie-build";
const LIVE_DIR_NAME = "live";
const GENERATION_DIR_PREFIX = "gen-";

export class GamePackageGenerator implements GamePackageGenerating {
    private readonly pokieVersion: string;

    constructor(pokieVersion: string) {
        this.pokieVersion = pokieVersion;
    }

    // "sourcePath" is optional and purely informational: when given (BuildCommand passes the
    // <config.json> path it was invoked with), it's recorded in build-info.json for provenance.
    // Omitting it — e.g. when calling the generator directly with an in-memory blueprint — still
    // produces a fully valid package, just without a "source" field.
    //
    // "blueprint" here is the blueprint exactly as authored/validated — including its per-reel
    // reelStripGeneration array, if any. "reelStripGeneration" is that array's *already resolved*
    // result (see resolveReelStripGeneration.ts) — normally BuildCommand runs resolution itself first
    // (so it can report per-reel diagnostics its own way) and passes the result straight through. A
    // caller that omits it entirely — e.g. calling this generator directly with an in-memory blueprint
    // — gets resolution run for it right here, failing the same way BuildCommand would have.
    // blueprintHash/no-op-rebuild detection (see buildGameBuildInfo) are therefore keyed on the
    // *authored* config, not on whatever a generated reel happened to produce — two different authored
    // configs that happen to generate byte-identical strips still hash differently. The actual runtime
    // file (index.js) instead gets a *materialized* copy (materializeReelStrips) with reelStripGeneration
    // resolved into a plain reelStrips array — the runtime module never depends on the generation API.
    public generate(
        blueprint: GameBlueprint,
        cwd: string,
        outDir?: string,
        sourcePath?: string,
        reelStripGeneration?: GameBuildInfoReelStripGeneration,
    ): GeneratedGamePackage {
        const id = blueprint.manifest.id;
        if (outDir === undefined && (id.includes("/") || id.includes("\\") || id === "." || id === "..")) {
            throw new Error(
                `"manifest.id" ("${id}") is not a valid directory name. Use a plain name, e.g. "sample-slot", or pass --out <dir>.`,
            );
        }

        const resolvedReelStripGeneration =
            reelStripGeneration !== undefined ? reelStripGeneration : this.resolveReelStripGenerationOrThrow(blueprint);

        const projectRoot = outDir !== undefined ? path.resolve(cwd, outDir) : path.join(cwd, id);
        const projectRootExists = fs.existsSync(projectRoot);
        // Validates the existing layout (including every public generated-file path's own type/target)
        // before anything below ever reads through one of those paths -- readPreviousBuildInfo included.
        if (projectRootExists) {
            this.assertSafeToRebuild(projectRoot);
        }
        const previousBuildInfo = projectRootExists ? this.readPreviousBuildInfo(projectRoot) : undefined;

        const buildInfo = buildGameBuildInfo(
            blueprint,
            this.pokieVersion,
            sourcePath,
            new Date(),
            GENERATED_PACKAGE_FILES,
            previousBuildInfo,
            resolvedReelStripGeneration,
        );

        const packageJson = {
            name: id,
            version: blueprint.manifest.version,
            description: blueprint.manifest.description ?? DEFAULT_DESCRIPTION,
            ...(blueprint.manifest.author ? {author: blueprint.manifest.author} : {}),
            keywords: ["pokie", "video-slot", "generated"],
            private: true,
            scripts: {
                start: "pokie dev .",
                server: "pokie serve .",
                client: "pokie client .",
            },
            dependencies: {
                pokie: `^${this.pokieVersion}`,
            },
            pokie: {
                entry: "./src/generated/index.js",
            },
        };

        // materializeReelStrips can throw (see its own fail-fast checks) — it runs before any
        // filesystem write below (including the staged directory this generator writes into first) so
        // a failure never creates or modifies anything, whether it's this call's own resolution or a
        // caller-supplied one.
        const materializedBlueprint = materializeReelStrips(blueprint, resolvedReelStripGeneration);

        this.publishGeneratedFiles(projectRoot, {
            "package.json": `${JSON.stringify(packageJson, null, 4)}\n`,
            "README.md": renderGeneratedPackageReadme(blueprint.manifest),
            "src/generated/index.js": renderGeneratedGameModule(materializedBlueprint, buildInfo),
            "src/generated/build-info.json": `${JSON.stringify(buildInfo, null, 4)}\n`,
        });

        return {
            projectRoot,
            manifest: blueprint.manifest,
            createdFiles: [...GENERATED_PACKAGE_FILES],
            buildInfo,
            unchanged: previousBuildInfo !== undefined && buildInfo.generatedAt === previousBuildInfo.generatedAt,
        };
    }

    // Publishes a whole generated package as one atomic unit: every file is staged into a fresh temp
    // sibling directory first (touching nothing under projectRoot), that staged set is committed into its
    // own permanent GENERATIONS_DIR_NAME generation directory, and LIVE_DIR_NAME — a symlink, never a
    // real directory — is then repointed at it with a single symlink-over-symlink rename (see
    // publishLiveGeneration). The four fixed public paths (package.json, README.md, src/generated/
    // index.js, src/generated/build-info.json) are symlinks permanently wired through LIVE_DIR_NAME (see
    // ensurePublicSymlinks), so that one rename is the *only* moment any of the four ever change what
    // they resolve to, and it changes what all four resolve to at once: a reader following any of them
    // can only ever observe the complete previous build or the complete new one — never a file from one
    // and a file from another, and never a moment where LIVE_DIR_NAME (and so every public path) resolves
    // to nothing at all.
    //
    // The *very first* publish for a given projectRoot is a deliberate exception: with nothing previously
    // consumable there, there's no "old" state a "new" one could ever be mixed with — so it writes plain,
    // independently relocatable files, exactly what this method always did before the live-directory
    // scheme existed, rather than the symlink indirection every later rebuild uses. This isn't just an
    // optimization: callers are entitled to rely on the *files* themselves being plain. applyGameBlueprintToProject,
    // for one, points this generator at a throwaway staging directory it always creates fresh and then
    // commits by picking each of the four files apart and renaming it into the real project individually
    // — a relative symlink surviving that individual relocation would resolve to nothing.
    //
    // That doesn't mean a concurrent reader of projectRoot is unprotected, though: when projectRoot is
    // itself fresh (missing, or present but empty — the case every real first build and every one of
    // applyGameBlueprintToProject's always-fresh staging directories is in), publishFirstBuild commits the
    // whole package with one directory rename (see publishAtomicFirstBuild), so a reader can only ever see
    // projectRoot missing/empty or fully populated — never some of the four files without the rest. Only
    // a first build into a projectRoot that already holds unrelated content (so the whole directory can't
    // be swapped in one step without disturbing it) falls back to committing the four files individually
    // (see publishPlainFiles) — there being no way to protect a reader of *that* directory from observing
    // the files land one at a time without risking the unrelated content it doesn't own.
    //
    // A projectRoot's *second* publish is the other deliberate exception: it migrates the first publish's
    // plain files onto the live-directory/symlink scheme (see migrateToLiveScheme) — every rebuild after
    // that continues using it via publishLiveGeneration alone.
    private publishGeneratedFiles(projectRoot: string, contentsByRelativePath: Record<string, string>): void {
        const relativePaths = Object.keys(contentsByRelativePath);
        const tempDir = `${projectRoot}.tmp-${crypto.randomBytes(6).toString("hex")}`;

        try {
            for (const relativePath of relativePaths) {
                const tempPath = path.join(tempDir, ...relativePath.split("/"));
                fs.mkdirSync(path.dirname(tempPath), {recursive: true});
                fs.writeFileSync(tempPath, contentsByRelativePath[relativePath]);
            }
        } catch (error) {
            this.removeBestEffort(tempDir);
            throw error;
        }

        // Only reached once staging above has fully succeeded, so a staging failure never creates or
        // modifies anything under projectRoot at all.
        const generationsDir = path.join(projectRoot, GENERATIONS_DIR_NAME);
        const liveLinkPath = path.join(generationsDir, LIVE_DIR_NAME);
        const liveAlreadyEstablished = this.isSymlink(liveLinkPath);
        const hasPriorPublish =
            liveAlreadyEstablished ||
            relativePaths.some((relativePath) => this.pathExists(path.join(projectRoot, ...relativePath.split("/"))));

        if (!hasPriorPublish) {
            this.publishFirstBuild(tempDir, projectRoot, relativePaths);
            return;
        }

        fs.mkdirSync(generationsDir, {recursive: true});

        if (!liveAlreadyEstablished) {
            this.migrateToLiveScheme(tempDir, projectRoot, generationsDir, liveLinkPath, relativePaths);
            return;
        }

        this.publishLiveGeneration(tempDir, generationsDir, liveLinkPath);
    }

    // A projectRoot's very first publish, dispatched to whichever of the two paths below can actually
    // commit it without ever exposing a reader to a subset of GENERATED_PACKAGE_FILES. Both leave the
    // four public paths as plain, independently relocatable files — never symlinks — for the reasons
    // publishGeneratedFiles documents.
    private publishFirstBuild(tempDir: string, projectRoot: string, relativePaths: string[]): void {
        if (this.isMissingOrEmptyDirectory(projectRoot)) {
            this.publishAtomicFirstBuild(tempDir, projectRoot);
            return;
        }
        this.publishPlainFiles(tempDir, projectRoot, relativePaths);
    }

    // True when projectRoot is either absent or an existing-but-empty directory — the only two states a
    // single directory rename can safely replace, since neither holds any content of its own that a
    // whole-directory swap would disturb. assertSafeToRebuild has already run by the time this is called
    // (see generate()), so an existing projectRoot is guaranteed to actually be a directory here.
    private isMissingOrEmptyDirectory(projectRoot: string): boolean {
        if (!fs.existsSync(projectRoot)) {
            return true;
        }
        return fs.readdirSync(projectRoot).length === 0;
    }

    // Commits every staged file at once by renaming the whole "tempDir" over projectRoot in a single
    // syscall — the only case where the *directory itself*, not just each file within it, can be swapped
    // atomically, since projectRoot is guaranteed empty (or absent) here (see isMissingOrEmptyDirectory).
    // Renaming a directory over an existing *empty* directory is itself atomic (same primitive
    // publishLiveGeneration relies on to rename a symlink over "live"), so a reader can only ever observe
    // projectRoot missing/empty or fully populated with all four files — never anything in between. A
    // failure here leaves projectRoot exactly as it was found (missing, or still the same empty
    // directory) and removes only the never-published "tempDir".
    private publishAtomicFirstBuild(tempDir: string, projectRoot: string): void {
        try {
            fs.renameSync(tempDir, projectRoot);
        } catch (error) {
            this.removeBestEffort(tempDir);
            throw error;
        }
    }

    // Commits every staged file directly into place as a plain file — a straight rename each, rolled
    // back (in reverse order) if a later one fails. Used only when a projectRoot's very first publish
    // lands in a directory that already holds unrelated content of its own (so the whole directory can't
    // be swapped in one step — see publishFirstBuild): there being no previous *package* here means a
    // partial failure has no package to preserve, just nothing new left half-written; a concurrent reader
    // watching the individual public paths land one at a time is the one exposure this fallback can't
    // close without risking the unrelated content it doesn't own.
    private publishPlainFiles(tempDir: string, projectRoot: string, relativePaths: string[]): void {
        const committed: string[] = [];
        for (const relativePath of relativePaths) {
            const realPath = path.join(projectRoot, ...relativePath.split("/"));
            try {
                fs.mkdirSync(path.dirname(realPath), {recursive: true});
                fs.renameSync(path.join(tempDir, ...relativePath.split("/")), realPath);
            } catch (error) {
                committed.forEach((alreadyCommittedPath) => fs.rmSync(alreadyCommittedPath, {recursive: true, force: true}));
                this.removeBestEffort(tempDir);
                throw error;
            }
            committed.push(realPath);
        }
        this.removeBestEffort(tempDir);
    }

    // A projectRoot's very first rebuild after its initial (plain-file) publish must move that
    // already-consumed package onto the live-directory/symlink indirection without ever letting a reader
    // observe a mix of the two. It does that in two phases: first, a purely structural one that changes
    // nothing observable — the current (old) content of every public path is cloned, byte for byte, into
    // its own generation directory, "live" is pointed at that clone, and every public path is then
    // rewired to a symlink through "live" (see ensurePublicSymlinks), so each one keeps resolving to
    // exactly the content it always had. Only once every path is safely wired to the clone does the
    // second phase run: publishLiveGeneration, the same single atomic swap an ordinary rebuild uses
    // forever after, which is what actually makes the newly staged build visible.
    //
    // A failure in the first phase restores every public path ensurePublicSymlinks already touched back
    // to its original plain file (that method's own rollback) and removes the clone and "live" symlink
    // this attempt created, leaving no unpublished candidate behind. A failure in publishLiveGeneration
    // (the second phase) leaves "live" pointed at the untouched clone — the package stays fully
    // consumable, just permanently on the symlink scheme a bit earlier than the content that failed to
    // publish would have changed it.
    private migrateToLiveScheme(
        tempDir: string,
        projectRoot: string,
        generationsDir: string,
        liveLinkPath: string,
        relativePaths: string[],
    ): void {
        const priorGenerationDir = this.newGenerationDirPath(generationsDir);

        try {
            fs.mkdirSync(priorGenerationDir, {recursive: true});
            for (const relativePath of relativePaths) {
                const realPath = path.join(projectRoot, ...relativePath.split("/"));
                const clonePath = path.join(priorGenerationDir, ...relativePath.split("/"));
                fs.mkdirSync(path.dirname(clonePath), {recursive: true});
                fs.copyFileSync(realPath, clonePath);
            }
            fs.symlinkSync(path.basename(priorGenerationDir), liveLinkPath);
        } catch (error) {
            this.removeBestEffort(liveLinkPath);
            this.removeBestEffort(priorGenerationDir);
            this.removeBestEffort(tempDir);
            throw error;
        }

        try {
            this.ensurePublicSymlinks(projectRoot, liveLinkPath, relativePaths);
        } catch (error) {
            this.removeBestEffort(liveLinkPath);
            this.removeBestEffort(priorGenerationDir);
            this.removeBestEffort(tempDir);
            throw error;
        }

        this.publishLiveGeneration(tempDir, generationsDir, liveLinkPath);
    }

    // Publishes the freshly staged "tempDir" by committing it into its own permanent generation
    // directory (a rename, so the live swap below never has to move real file content) and then
    // repointing LIVE_DIR_NAME at it: a brand-new symlink is created under a throwaway name and *that* is
    // renamed over LIVE_DIR_NAME in one syscall. Renaming a symlink over an existing one is atomic —
    // LIVE_DIR_NAME is either the previous generation or the new one for any onlooker, never briefly
    // missing, unlike this generator's previous approach of renaming the live directory's actual content
    // aside and back in two separate steps. A failure at either step leaves the previous LIVE_DIR_NAME
    // (if any) completely untouched, since nothing at its path is ever modified until the final rename
    // succeeds; only the new, not-yet-published generation directory and throwaway symlink are cleaned up.
    private publishLiveGeneration(tempDir: string, generationsDir: string, liveLinkPath: string): void {
        const newGenerationDir = this.newGenerationDirPath(generationsDir);
        try {
            fs.renameSync(tempDir, newGenerationDir);
        } catch (error) {
            this.removeBestEffort(tempDir);
            throw error;
        }

        const previousTarget = this.readLiveTarget(generationsDir, liveLinkPath);
        const tempLinkPath = `${liveLinkPath}.tmp-${crypto.randomBytes(6).toString("hex")}`;

        try {
            fs.symlinkSync(path.basename(newGenerationDir), tempLinkPath);
            fs.renameSync(tempLinkPath, liveLinkPath);
        } catch (error) {
            this.removeBestEffort(tempLinkPath);
            this.removeBestEffort(newGenerationDir);
            throw error;
        }

        if (previousTarget !== undefined) {
            this.removeBestEffort(previousTarget);
        }
    }

    private newGenerationDirPath(generationsDir: string): string {
        return path.join(generationsDir, `${GENERATION_DIR_PREFIX}${crypto.randomBytes(6).toString("hex")}`);
    }

    // Resolves LIVE_DIR_NAME's current target to an absolute path, or undefined if it doesn't exist (or
    // isn't a symlink) — used only to know what to remove, best-effort, after a swap has already
    // succeeded and made that target unreachable from every public path.
    private readLiveTarget(generationsDir: string, liveLinkPath: string): string | undefined {
        try {
            return path.resolve(generationsDir, fs.readlinkSync(liveLinkPath));
        } catch {
            return undefined;
        }
    }

    private isSymlink(targetPath: string): boolean {
        try {
            return fs.lstatSync(targetPath).isSymbolicLink();
        } catch {
            return false;
        }
    }

    // Wires each of the four fixed public paths up as a symlink into LIVE_DIR_NAME. A path that's already
    // correctly symlinked there (every rebuild after migration, since publishLiveGeneration is the only
    // thing that ever changes what LIVE_DIR_NAME points to) is left completely untouched — this method's
    // own file-touching work runs at most once per path, only during migrateToLiveScheme. Anything else
    // already at a path — a legacy plain file, or a symlink pointing somewhere unexpected — is replaced by
    // a single rename of a freshly built symlink over it (the same rename-a-throwaway-symlink-into-place
    // trick publishLiveGeneration uses for "live" itself), never by renaming the existing path away first:
    // that path therefore always resolves to *something* — its original content, then its new symlink —
    // and never briefly to nothing. Before that replacing rename, the original content is preserved by
    // *copying* it aside (not moving it), so a failure partway through this call can still restore every
    // path it already touched back to exactly what it held before, leaving the prior package fully intact
    // with no manual recovery.
    private ensurePublicSymlinks(projectRoot: string, liveLinkPath: string, relativePaths: string[]): void {
        const touched: {realPath: string; stalePath: string | undefined}[] = [];

        for (const relativePath of relativePaths) {
            const realPath = path.join(projectRoot, ...relativePath.split("/"));
            const targetPath = path.join(liveLinkPath, ...relativePath.split("/"));
            const expectedTarget = path.relative(path.dirname(realPath), targetPath);

            if (this.isAlreadyCorrectSymlink(realPath, expectedTarget)) {
                continue;
            }

            const stalePath = this.pathExists(realPath) ? `${realPath}.stale-${crypto.randomBytes(6).toString("hex")}` : undefined;
            if (stalePath !== undefined) {
                try {
                    this.copyPreservingType(realPath, stalePath);
                } catch (error) {
                    this.removeBestEffort(stalePath);
                    this.rollBackTouchedSymlinks(touched);
                    throw error;
                }
            }

            const tempLinkPath = `${realPath}.tmp-${crypto.randomBytes(6).toString("hex")}`;
            try {
                fs.mkdirSync(path.dirname(realPath), {recursive: true});
                fs.symlinkSync(expectedTarget, tempLinkPath);
                fs.renameSync(tempLinkPath, realPath);
            } catch (error) {
                this.removeBestEffort(tempLinkPath);
                if (stalePath !== undefined) {
                    this.removeBestEffort(stalePath);
                }
                this.rollBackTouchedSymlinks(touched);
                throw error;
            }
            touched.push({realPath, stalePath});
        }

        touched.forEach(({stalePath}) => {
            if (stalePath !== undefined) {
                this.removeBestEffort(stalePath);
            }
        });
    }

    // Copies whatever is at "sourcePath" to "destinationPath" without disturbing "sourcePath" itself —
    // used to preserve a public path's pre-migration content for rollback purposes while the real
    // replacement happens via a rename over "sourcePath" (never a move away from it). A symlink is
    // recreated pointing at the same target (its referent is never dereferenced/copied); anything else
    // (the plain files this generator's very first publish always writes) is copied byte for byte.
    private copyPreservingType(sourcePath: string, destinationPath: string): void {
        if (fs.lstatSync(sourcePath).isSymbolicLink()) {
            fs.symlinkSync(fs.readlinkSync(sourcePath), destinationPath);
        } else {
            fs.copyFileSync(sourcePath, destinationPath);
        }
    }

    private isAlreadyCorrectSymlink(realPath: string, expectedTarget: string): boolean {
        try {
            return fs.readlinkSync(realPath) === expectedTarget;
        } catch {
            return false;
        }
    }

    private pathExists(targetPath: string): boolean {
        try {
            fs.lstatSync(targetPath);
            return true;
        } catch {
            return false;
        }
    }

    // Rolls every already-wired symlink back to what its path held before (reverse order) — used when a
    // *different* path in the same publish failed to wire up, so none of the others may end up ahead of
    // it. Restoring a path that had prior content renames its preserved copy back over the new symlink —
    // an atomic replace, exactly mirroring how that symlink got wired in the first place, so the path
    // never resolves to nothing during rollback either. A path that had nothing before (no stalePath) is
    // simply removed. A blind restore is safe here: nothing but this generator itself ever writes these
    // paths.
    private rollBackTouchedSymlinks(touched: {realPath: string; stalePath: string | undefined}[]): void {
        for (const {realPath, stalePath} of [...touched].reverse()) {
            if (stalePath !== undefined) {
                fs.renameSync(stalePath, realPath);
            } else {
                fs.rmSync(realPath, {recursive: true, force: true});
            }
        }
    }

    private removeBestEffort(targetPath: string): void {
        try {
            fs.rmSync(targetPath, {recursive: true, force: true});
        } catch {
            // best-effort only.
        }
    }

    // Runs resolveReelStripGeneration for a caller that didn't already do so (and pass its result in)
    // — mirrors what BuildCommand does with its own console.error reporting, but as a single thrown
    // error carrying every failed reel's diagnostics, since a direct caller has no per-reel reporting
    // of its own to hook into.
    private resolveReelStripGenerationOrThrow(blueprint: GameBlueprint): GameBuildInfoReelStripGeneration | undefined {
        const resolution = resolveReelStripGeneration(blueprint);
        if (resolution.success) {
            return resolution.reelStripGeneration;
        }

        const lines = resolution.reels
            .filter((reel) => !reel.success)
            .map((reel) => {
                const lastDiagnostic = reel.diagnostics[reel.diagnostics.length - 1];
                const violationLines = (lastDiagnostic?.violations ?? [])
                    .map((violation) => `      ${violation.constraintId}: ${violation.message}`)
                    .join("\n");
                return (
                    `  - reel ${reel.reelIndex} (seed ${reel.seed}): failed after ${reel.attemptsUsed} attempt(s)` +
                    (violationLines ? `\n${violationLines}` : "")
                );
            });

        throw new Error(`Blueprint "${blueprint.manifest.id}" could not generate its reel strips:\n${lines.join("\n")}`);
    }

    // Refuses to build into an existing, non-empty directory unless every fixed path we're about to
    // write (GENERATED_PACKAGE_FILES) is either absent or already known to have been produced by a
    // prior "pokie build" run. That's what lets re-running "pokie build" into the same --out directory
    // (e.g. after editing the blueprint) overwrite cleanly, while a directory that happens to already
    // have its own unrelated package.json/README.md/etc. is left untouched and reported as a conflict
    // instead of silently clobbered.
    //
    // "Known to have been produced by pokie build" is read from the existing directory's own
    // src/generated/build-info.json — itself pokie build output — rather than assumed: its "files"
    // field lists exactly what that run generated, so a newer generator recognizes an older one's
    // output even if the generated file set has changed since.
    private assertSafeToRebuild(projectRoot: string): void {
        if (!fs.statSync(projectRoot).isDirectory()) {
            throw new Error(
                `"${projectRoot}" already exists and is not a directory. Choose a different --out directory or remove it first.`,
            );
        }

        // Runs unconditionally, before any recognition check below: an attacker planting a bogus
        // GENERATIONS_DIR_NAME/LIVE_DIR_NAME doesn't need a convincing build-info.json alongside it, so
        // this can't be gated on one having been found.
        this.assertTrustedGenerationsLayout(projectRoot);

        // Also unconditional, and also before any recognition check: a known-recognized package (via
        // build-info.json's "files") is not enough to trust what's actually sitting at each of those
        // paths right now -- see assertTrustedPublicPaths.
        const liveLinkPath = path.join(projectRoot, GENERATIONS_DIR_NAME, LIVE_DIR_NAME);
        this.assertTrustedPublicPaths(projectRoot, liveLinkPath);

        const knownFiles = this.readKnownGeneratedFiles(projectRoot);
        const conflicting = GENERATED_PACKAGE_FILES.filter(
            (relativePath) => !knownFiles.includes(relativePath) && fs.existsSync(path.join(projectRoot, ...relativePath.split("/"))),
        );

        if (conflicting.length > 0) {
            throw new Error(
                `"${projectRoot}" already exists and contains file(s) "pokie build" did not generate: ${conflicting.join(", ")}. ` +
                    `Refusing to overwrite them — choose a different --out directory, remove the conflicting file(s), or point ` +
                    `--out at a directory previously produced by "pokie build" (recognized via its own src/generated/build-info.json).`,
            );
        }

        // A directory not yet migrated onto the live-directory scheme (see migrateToLiveScheme) is
        // "known" only via its plain files themselves -- if any of those the prior build vouches for
        // is now missing, the layout is an ambiguous partial one that migrateToLiveScheme has no safe
        // way to clone from (it would discover the gap mid-clone, after already committing to a
        // rebuild). Fail closed here instead, before generate() does anything else.
        if (knownFiles.length > 0 && !this.pathExists(liveLinkPath)) {
            const missing = knownFiles.filter(
                (relativePath) => !fs.existsSync(path.join(projectRoot, ...relativePath.split("/"))),
            );
            if (missing.length > 0) {
                throw new Error(
                    `"${projectRoot}" is missing file(s) a previous "pokie build" generated: ${missing.join(", ")}. ` +
                        `Refusing to rebuild an incomplete package — restore the missing file(s), or remove "${projectRoot}" ` +
                        `and run "pokie build" fresh.`,
                );
            }
        }
    }

    // Validates GENERATIONS_DIR_NAME/LIVE_DIR_NAME before generate() does anything else that could
    // read or delete through them (migrateToLiveScheme's clone, or publishLiveGeneration's
    // removeBestEffort(previousTarget) — see readLiveTarget). GENERATIONS_DIR_NAME not existing at all
    // is the ordinary case for every rebuild before migrateToLiveScheme's first run, and is left alone.
    // Once it exists, it must be exactly what this generator itself would ever produce: a real
    // (non-symlink) directory, whose LIVE_DIR_NAME entry (if present) is a symlink -- never a plain
    // file or real directory -- resolving to a GENERATION_DIR_PREFIX-named directory physically
    // contained inside GENERATIONS_DIR_NAME's own resolved location. Anything short of that -- a
    // symlink escaping containment, a dangling target, or a hand-placed non-symlink "live" -- fails
    // closed here with an actionable error, rather than being silently followed (and possibly deleted)
    // or silently overwritten.
    private assertTrustedGenerationsLayout(projectRoot: string): void {
        const generationsDir = path.join(projectRoot, GENERATIONS_DIR_NAME);
        if (!this.pathExists(generationsDir)) {
            return;
        }

        const remediation = `Refusing to rebuild — remove "${generationsDir}" (or all of "${projectRoot}") and run "pokie build" fresh.`;

        if (this.isSymlink(generationsDir) || !fs.statSync(generationsDir).isDirectory()) {
            throw new Error(`"${generationsDir}" is not a directory this generator produced. ${remediation}`);
        }

        const liveLinkPath = path.join(generationsDir, LIVE_DIR_NAME);
        if (!this.pathExists(liveLinkPath)) {
            return;
        }

        if (!this.isSymlink(liveLinkPath)) {
            throw new Error(`"${liveLinkPath}" already exists but is not a symlink this generator produced. ${remediation}`);
        }

        let resolvedGenerationsDir: string;
        let resolvedLiveTarget: string;
        try {
            resolvedGenerationsDir = fs.realpathSync(generationsDir);
            resolvedLiveTarget = fs.realpathSync(liveLinkPath);
        } catch {
            throw new Error(`"${liveLinkPath}" points at a generation that no longer exists. ${remediation}`);
        }

        const isContained = resolvedLiveTarget.startsWith(`${resolvedGenerationsDir}${path.sep}`);
        const ownsBasename = path.basename(resolvedLiveTarget).startsWith(GENERATION_DIR_PREFIX);

        if (!isContained || !ownsBasename || !fs.statSync(resolvedLiveTarget).isDirectory()) {
            throw new Error(
                `"${liveLinkPath}" does not point at a generation this generator produced (expected a ` +
                    `"${GENERATION_DIR_PREFIX}*" directory contained in "${generationsDir}"). ${remediation}`,
            );
        }
    }

    // Validates each of the four fixed public paths (GENERATED_PACKAGE_FILES) before generate() does
    // anything that would trust their current type or target: migrateToLiveScheme's fs.copyFileSync
    // clone (which *follows* a symlink to read its target's bytes) if this package hasn't reached the
    // live-directory scheme yet, or the fact that an ordinary rebuild past that point never re-touches
    // the public paths at all -- it only repoints LIVE_DIR_NAME, so a public path that's since been
    // swapped out from under this generator would otherwise keep resolving to whatever an attacker put
    // there, silently out of sync with every future "live" build. Recognizing a package (via a
    // convincing build-info.json) is not enough on its own; what's actually sitting at each path right
    // now must independently match what this generator would have put there:
    //  - before migration, every public path that exists must be a plain regular file -- never a
    //    symlink (publishPlainFiles/ensurePublicSymlinks are the only things that ever create these
    //    paths, and neither ever writes a symlink before migration has happened) or anything else.
    //  - once migrated, every public path must exist and be exactly the relative symlink through
    //    LIVE_DIR_NAME that ensurePublicSymlinks would itself have wired up for it.
    // Every check here is lstat/readlink-based -- a symlink's target is never dereferenced, read,
    // copied, or written -- so a hostile target is inert no matter which branch rejects it.
    private assertTrustedPublicPaths(projectRoot: string, liveLinkPath: string): void {
        const liveEstablished = this.isSymlink(liveLinkPath);
        const remediation = `Refusing to rebuild "${projectRoot}" -- remove the conflicting file(s) (or all of "${projectRoot}") and run "pokie build" fresh.`;

        for (const relativePath of GENERATED_PACKAGE_FILES) {
            const realPath = path.join(projectRoot, ...relativePath.split("/"));

            let stats: fs.Stats | undefined;
            try {
                stats = fs.lstatSync(realPath);
            } catch {
                stats = undefined;
            }

            if (!liveEstablished) {
                if (stats !== undefined && !stats.isFile()) {
                    throw new Error(
                        `"${realPath}" is a ${stats.isSymbolicLink() ? "symlink" : stats.isDirectory() ? "directory" : "special file"}, ` +
                            `not the plain file "pokie build" writes before a package has migrated onto its live-directory scheme. ${remediation}`,
                    );
                }
                continue;
            }

            if (stats === undefined) {
                throw new Error(
                    `"${realPath}" is missing, but "pokie build" already migrated "${projectRoot}" onto its live-directory scheme. ${remediation}`,
                );
            }

            const expectedTarget = path.relative(path.dirname(realPath), path.join(liveLinkPath, ...relativePath.split("/")));
            if (!stats.isSymbolicLink() || !this.isAlreadyCorrectSymlink(realPath, expectedTarget)) {
                throw new Error(
                    `"${realPath}" is not the symlink "pokie build" expects through "${liveLinkPath}". ${remediation}`,
                );
            }

            this.assertTrustedLiveGenerationEntry(liveLinkPath, relativePath);
        }
    }

    // Proves what a public path's symlink actually resolves to *inside* the live generation is itself a
    // plain regular file, before readPreviousBuildInfo (or any future rebuild path) reads through it.
    // assertTrustedPublicPaths above only checks the public path's own symlink *text* -- that it points
    // into liveLinkPath at the expected relative location -- which says nothing about what's actually
    // sitting there: assertTrustedGenerationsLayout vouches for liveLinkPath and the generation directory
    // containing it, never for the individual files (or intermediate directories, e.g. "src" or
    // "src/generated") inside that directory. Nothing here planted those itself except this generator,
    // but an attacker able to write under GENERATIONS_DIR_NAME (e.g. directly into a generation
    // directory, before or after "live" is pointed at it) could still make an *intermediate* ancestor of
    // a leaf entry a symlink to an arbitrary external directory, so that a plain-looking leaf name
    // (build-info.json, most exploitably, since readPreviousBuildInfo reads it) actually resolves outside
    // the generation entirely once the OS follows that ancestor during path resolution -- lstat on the
    // leaf alone would not catch this, since lstat only refuses to follow the *final* path component.
    // So every ancestor component from liveLinkPath down to the leaf's parent is walked and lstat'd
    // (never following the final component of any single lstat call) one directory at a time, confirming
    // each is a real (non-symlink) directory before the next component is even joined onto the path being
    // checked, before the leaf itself is lstat'd for the plain-regular-file check. A hostile ancestor or
    // leaf is therefore rejected here, not followed: nothing it points at is ever opened, read, or written.
    private assertTrustedLiveGenerationEntry(liveLinkPath: string, relativePath: string): void {
        const remediation = `Refusing to rebuild -- remove "${liveLinkPath}" (or the whole "${path.dirname(liveLinkPath)}") and run "pokie build" fresh.`;
        const segments = relativePath.split("/");

        let currentPath = liveLinkPath;
        for (let i = 0; i < segments.length - 1; i++) {
            currentPath = path.join(currentPath, segments[i]);

            let dirStats: fs.Stats;
            try {
                dirStats = fs.lstatSync(currentPath);
            } catch {
                throw new Error(`"${currentPath}" is missing from the current live generation. ${remediation}`);
            }

            if (!dirStats.isDirectory()) {
                throw new Error(
                    `"${currentPath}" is a ${dirStats.isSymbolicLink() ? "symlink" : "special file"}, ` +
                        `not the plain directory "pokie build" writes inside a generation directory. ${remediation}`,
                );
            }
        }

        const entryPath = path.join(currentPath, segments[segments.length - 1]);

        let stats: fs.Stats;
        try {
            stats = fs.lstatSync(entryPath);
        } catch {
            throw new Error(`"${entryPath}" is missing from the current live generation. ${remediation}`);
        }

        if (!stats.isFile()) {
            throw new Error(
                `"${entryPath}" is a ${stats.isSymbolicLink() ? "symlink" : stats.isDirectory() ? "directory" : "special file"}, ` +
                    `not the plain file "pokie build" writes inside a generation directory. ${remediation}`,
            );
        }
    }

    // Returns the file list an existing directory's own build-info.json vouches for, or [] if there's
    // no build-info.json there, it doesn't parse, or it wasn't written by "pokie build" — in which case
    // every fixed output path found on disk is treated as a conflict.
    private readKnownGeneratedFiles(projectRoot: string): string[] {
        const previous = this.readPreviousBuildInfo(projectRoot);
        if (previous === undefined) {
            return [];
        }
        return Array.isArray(previous.files) ? previous.files : GENERATED_PACKAGE_FILES;
    }

    // Returns the existing directory's own build-info.json, or undefined if there's none there, it
    // doesn't parse, or it wasn't written by "pokie build". Feeds both readKnownGeneratedFiles (the
    // rebuild-safety check) and buildGameBuildInfo (the generatedAt reuse-on-no-op-rebuild check).
    private readPreviousBuildInfo(projectRoot: string): GameBuildInfo | undefined {
        const buildInfoPath = path.join(projectRoot, ...BUILD_INFO_RELATIVE_PATH.split("/"));
        if (!fs.existsSync(buildInfoPath)) {
            return undefined;
        }

        try {
            const parsed = JSON.parse(fs.readFileSync(buildInfoPath, "utf-8"));
            if (!parsed || parsed.generatedBy !== "pokie build") {
                return undefined;
            }
            return parsed as GameBuildInfo;
        } catch {
            return undefined;
        }
    }
}
