import crypto from "crypto";
import fs from "fs";
import path from "path";
import {buildGameBuildInfo, GENERATED_PACKAGE_FILES} from "./buildGameBuildInfo.js";
import type {GameBlueprint} from "./GameBlueprint.js";
import type {GameBuildInfo} from "./GameBuildInfo.js";
import type {GameBuildInfoReelStripGeneration} from "./GameBuildInfoReelStripGeneration.js";
import type {GamePackageGenerating} from "./GamePackageGenerating.js";
import type {GeneratedGamePackage} from "./GeneratedGamePackage.js";
import {materializeReelStrips} from "./materializeReelStrips.js";
import {renderGeneratedGameModule} from "./renderGeneratedGameModule.js";
import {renderGeneratedPackageReadme} from "./renderGeneratedPackageReadme.js";
import {resolveReelStripGeneration} from "./resolveReelStripGeneration.js";

const DEFAULT_DESCRIPTION = 'Generated by "pokie build" — a POKIE video slot game package.';
const BUILD_INFO_RELATIVE_PATH = "src/generated/build-info.json";

export class GamePackageGenerator implements GamePackageGenerating {
    private readonly pokieVersion: string;

    constructor(pokieVersion: string) {
        this.pokieVersion = pokieVersion;
    }

    // "sourcePath" is optional and purely informational: when given (BuildCommand passes the
    // <config.json> path it was invoked with), it's recorded in build-info.json for provenance.
    // Omitting it — e.g. when calling the generator directly with an in-memory blueprint — still
    // produces a fully valid package, just without a "source" field.
    //
    // "blueprint" here is the blueprint exactly as authored/validated — including its per-reel
    // reelStripGeneration array, if any. "reelStripGeneration" is that array's *already resolved*
    // result (see resolveReelStripGeneration.ts) — normally BuildCommand runs resolution itself first
    // (so it can report per-reel diagnostics its own way) and passes the result straight through. A
    // caller that omits it entirely — e.g. calling this generator directly with an in-memory blueprint
    // — gets resolution run for it right here, failing the same way BuildCommand would have.
    // blueprintHash/no-op-rebuild detection (see buildGameBuildInfo) are therefore keyed on the
    // *authored* config, not on whatever a generated reel happened to produce — two different authored
    // configs that happen to generate byte-identical strips still hash differently. The actual runtime
    // file (index.js) instead gets a *materialized* copy (materializeReelStrips) with reelStripGeneration
    // resolved into a plain reelStrips array — the runtime module never depends on the generation API.
    public generate(
        blueprint: GameBlueprint,
        cwd: string,
        outDir?: string,
        sourcePath?: string,
        reelStripGeneration?: GameBuildInfoReelStripGeneration,
    ): GeneratedGamePackage {
        const id = blueprint.manifest.id;
        if (outDir === undefined && (id.includes("/") || id.includes("\\") || id === "." || id === "..")) {
            throw new Error(
                `"manifest.id" ("${id}") is not a valid directory name. Use a plain name, e.g. "sample-slot", or pass --out <dir>.`,
            );
        }

        const resolvedReelStripGeneration =
            reelStripGeneration !== undefined ? reelStripGeneration : this.resolveReelStripGenerationOrThrow(blueprint);

        const projectRoot = outDir !== undefined ? path.resolve(cwd, outDir) : path.join(cwd, id);
        const projectRootExists = fs.existsSync(projectRoot);
        // Validates the existing layout (including every public generated-file path's own type) before
        // anything below ever reads through one of those paths -- readPreviousBuildInfo included.
        if (projectRootExists) {
            this.assertSafeToRebuild(projectRoot);
        }
        const previousBuildInfo = projectRootExists ? this.readPreviousBuildInfo(projectRoot) : undefined;

        const buildInfo = buildGameBuildInfo(
            blueprint,
            this.pokieVersion,
            sourcePath,
            new Date(),
            GENERATED_PACKAGE_FILES,
            previousBuildInfo,
            resolvedReelStripGeneration,
        );

        const packageJson = {
            name: id,
            version: blueprint.manifest.version,
            description: blueprint.manifest.description ?? DEFAULT_DESCRIPTION,
            ...(blueprint.manifest.author ? {author: blueprint.manifest.author} : {}),
            keywords: ["pokie", "video-slot", "generated"],
            private: true,
            scripts: {
                start: "pokie dev .",
                server: "pokie serve .",
                client: "pokie client .",
            },
            dependencies: {
                pokie: `^${this.pokieVersion}`,
            },
            pokie: {
                entry: "./src/generated/index.js",
            },
        };

        // materializeReelStrips can throw (see its own fail-fast checks) — it runs before any
        // filesystem write below (including the staged directory this generator writes into first) so
        // a failure never creates or modifies anything, whether it's this call's own resolution or a
        // caller-supplied one.
        const materializedBlueprint = materializeReelStrips(blueprint, resolvedReelStripGeneration);

        this.publishGeneratedFiles(projectRoot, {
            "package.json": `${JSON.stringify(packageJson, null, 4)}\n`,
            "README.md": renderGeneratedPackageReadme(blueprint.manifest),
            "src/generated/index.js": renderGeneratedGameModule(materializedBlueprint, buildInfo),
            "src/generated/build-info.json": `${JSON.stringify(buildInfo, null, 4)}\n`,
        });

        return {
            projectRoot,
            manifest: blueprint.manifest,
            createdFiles: [...GENERATED_PACKAGE_FILES],
            buildInfo,
            unchanged: previousBuildInfo !== undefined && buildInfo.generatedAt === previousBuildInfo.generatedAt,
        };
    }

    // Publishes a whole generated package as one unit: every file is staged into a fresh temp sibling
    // directory first (touching nothing under projectRoot), and only once every one of them has been
    // written successfully is anything under projectRoot ever touched. The four fixed public paths
    // (package.json, README.md, src/generated/index.js, src/generated/build-info.json) are always plain,
    // independently relocatable files — never symlinks, and never reached through any indirection this
    // generator owns — so the generated package stays directly packageable (npm pack, tar, zip, ...)
    // regardless of what "pokie build" itself is doing on disk.
    //
    // The *very first* publish for a given projectRoot is committed with a single atomic directory
    // rename (see publishFirstBuild) whenever projectRoot is missing or empty, so a reader can only ever
    // observe projectRoot missing/empty or fully populated with all four files — never a subset of them.
    // A first build into a projectRoot that already holds unrelated content has no atomic way to add the
    // four public paths to it (there is no single syscall that commits several independent paths
    // together), so it's refused outright instead of ever being published one file at a time.
    //
    // Every publish after the first — a rebuild into a projectRoot this generator already published to
    // — commits each of the four files independently (see publishRebuild): the file already staged in
    // "tempDir" is renamed directly over its real, fixed path, replacing whatever was there in one
    // syscall (so that path is only ever its complete old content or its complete new content, never
    // partially written or briefly missing at rest). Since the four paths are independent, fixed
    // locations rather than one directory this generator could swap as a whole (package.json and
    // README.md sit directly in projectRoot, alongside whatever else lives there — node_modules, a
    // user's own files — that this generator has no business touching), there is no single syscall that
    // commits all four together; a failure partway through instead rolls every already-committed file in
    // this publish back to exactly what it held before (see publishRebuild), so the prior package is
    // always left fully intact and consumable, whatever fails and whenever it fails.
    private publishGeneratedFiles(projectRoot: string, contentsByRelativePath: Record<string, string>): void {
        const relativePaths = Object.keys(contentsByRelativePath);
        const tempDir = `${projectRoot}.tmp-${crypto.randomBytes(6).toString("hex")}`;

        try {
            for (const relativePath of relativePaths) {
                const tempPath = path.join(tempDir, ...relativePath.split("/"));
                fs.mkdirSync(path.dirname(tempPath), {recursive: true});
                fs.writeFileSync(tempPath, contentsByRelativePath[relativePath]);
            }
        } catch (error) {
            this.removeBestEffort(tempDir);
            throw error;
        }

        // Only reached once staging above has fully succeeded, so a staging failure never creates or
        // modifies anything under projectRoot at all.
        if (this.isMissingOrEmptyDirectory(projectRoot)) {
            this.publishAtomicFirstBuild(tempDir, projectRoot);
            return;
        }

        const hasPriorPublish = relativePaths.some((relativePath) => this.pathExists(path.join(projectRoot, ...relativePath.split("/"))));
        if (!hasPriorPublish) {
            this.removeBestEffort(tempDir);
            throw new Error(
                `"${projectRoot}" already exists and is not empty. The very first "pokie build" into a directory can only be ` +
                    `published atomically when that directory is missing or empty — publishing into a non-empty directory one ` +
                    `file at a time could expose a partial package. Remove or empty "${projectRoot}" first, or build into a ` +
                    `different --out directory, and run "pokie build" again.`,
            );
        }

        this.publishRebuild(tempDir, projectRoot, relativePaths);
    }

    // True when projectRoot is either absent or an existing-but-empty directory — the only two states a
    // single directory rename can safely replace, since neither holds any content of its own that a
    // whole-directory swap would disturb. assertSafeToRebuild has already run by the time this is called
    // (see generate()), so an existing projectRoot is guaranteed to actually be a directory here.
    private isMissingOrEmptyDirectory(projectRoot: string): boolean {
        if (!fs.existsSync(projectRoot)) {
            return true;
        }
        return fs.readdirSync(projectRoot).length === 0;
    }

    // Commits every staged file at once by renaming the whole "tempDir" over projectRoot in a single
    // syscall — the only case where the *directory itself*, not just each file within it, can be swapped
    // atomically, since projectRoot is guaranteed empty (or absent) here (see isMissingOrEmptyDirectory).
    // Renaming a directory over an existing *empty* directory is itself atomic, so a reader can only
    // ever observe projectRoot missing/empty or fully populated with all four files — never anything in
    // between. A failure here leaves projectRoot exactly as it was found (missing, or still the same
    // empty directory) and removes only the never-published "tempDir".
    private publishAtomicFirstBuild(tempDir: string, projectRoot: string): void {
        try {
            fs.renameSync(tempDir, projectRoot);
        } catch (error) {
            this.removeBestEffort(tempDir);
            throw error;
        }
    }

    // Commits a rebuild into a projectRoot that already holds a prior, consumable publish: each staged
    // file is moved onto its real, fixed path one at a time — whatever currently sits there is first
    // renamed aside (never copied; the move itself is what frees the real path's name for the incoming
    // file), then the staged file is renamed into the now-free name. Both renames replace/create a
    // single non-directory path each, so the operation as a whole can only ever leave that real path
    // holding its complete previous content or its complete new content — never truncated or
    // half-written. A failure at either step — this file's own commit, or a later file's in the same
    // publish — rolls every file this publish already committed back to its stale copy, in reverse
    // order, so nothing in this rebuild is ever left ahead of the rest; the whole prior package is left
    // exactly as it was found. This mirrors the same "rename aside, rename in, restore on failure"
    // pattern applyGameBlueprintToProject.ts uses (via commitStagedPath.ts) to commit these same four
    // files into a live project directory it doesn't otherwise control.
    private publishRebuild(tempDir: string, projectRoot: string, relativePaths: string[]): void {
        const committed: {realPath: string; stalePath: string | undefined}[] = [];

        for (const relativePath of relativePaths) {
            const realPath = path.join(projectRoot, ...relativePath.split("/"));
            const tempPath = path.join(tempDir, ...relativePath.split("/"));

            let stalePath: string | undefined;
            if (this.pathExists(realPath)) {
                stalePath = `${realPath}.stale-${crypto.randomBytes(6).toString("hex")}`;
                try {
                    fs.renameSync(realPath, stalePath);
                } catch (error) {
                    this.rollBackCommittedFiles(committed);
                    this.removeBestEffort(tempDir);
                    throw error;
                }
            }

            try {
                fs.renameSync(tempPath, realPath);
            } catch (error) {
                if (stalePath !== undefined) {
                    fs.renameSync(stalePath, realPath);
                }
                this.rollBackCommittedFiles(committed);
                this.removeBestEffort(tempDir);
                throw error;
            }

            committed.push({realPath, stalePath});
        }

        committed.forEach(({stalePath}) => {
            if (stalePath !== undefined) {
                this.removeBestEffort(stalePath);
            }
        });
        this.removeBestEffort(tempDir);
    }

    // Rolls every already-committed file in a failed publishRebuild back to what it held before (reverse
    // order) — used when a *different* file in the same publish failed to commit, so none of the others
    // may end up ahead of it. A blind restore is safe here: nothing but this generator itself ever writes
    // these paths (assertSafeToRebuild already vetted them before this publish began).
    private rollBackCommittedFiles(committed: {realPath: string; stalePath: string | undefined}[]): void {
        for (const {realPath, stalePath} of [...committed].reverse()) {
            if (stalePath !== undefined) {
                fs.renameSync(stalePath, realPath);
            } else {
                fs.rmSync(realPath, {recursive: true, force: true});
            }
        }
    }

    private pathExists(targetPath: string): boolean {
        try {
            fs.lstatSync(targetPath);
            return true;
        } catch {
            return false;
        }
    }

    private removeBestEffort(targetPath: string): void {
        try {
            fs.rmSync(targetPath, {recursive: true, force: true});
        } catch {
            // best-effort only.
        }
    }

    // Runs resolveReelStripGeneration for a caller that didn't already do so (and pass its result in)
    // — mirrors what BuildCommand does with its own console.error reporting, but as a single thrown
    // error carrying every failed reel's diagnostics, since a direct caller has no per-reel reporting
    // of its own to hook into.
    private resolveReelStripGenerationOrThrow(blueprint: GameBlueprint): GameBuildInfoReelStripGeneration | undefined {
        const resolution = resolveReelStripGeneration(blueprint);
        if (resolution.success) {
            return resolution.reelStripGeneration;
        }

        const lines = resolution.reels
            .filter((reel) => !reel.success)
            .map((reel) => {
                const lastDiagnostic = reel.diagnostics[reel.diagnostics.length - 1];
                const violationLines = (lastDiagnostic?.violations ?? [])
                    .map((violation) => `      ${violation.constraintId}: ${violation.message}`)
                    .join("\n");
                return (
                    `  - reel ${reel.reelIndex} (seed ${reel.seed}): failed after ${reel.attemptsUsed} attempt(s)` +
                    (violationLines ? `\n${violationLines}` : "")
                );
            });

        throw new Error(`Blueprint "${blueprint.manifest.id}" could not generate its reel strips:\n${lines.join("\n")}`);
    }

    // Refuses to build into an existing, non-empty directory unless every fixed path we're about to
    // write (GENERATED_PACKAGE_FILES) is either absent or already known to have been produced by a
    // prior "pokie build" run. That's what lets re-running "pokie build" into the same --out directory
    // (e.g. after editing the blueprint) overwrite cleanly, while a directory that happens to already
    // have its own unrelated package.json/README.md/etc. is left untouched and reported as a conflict
    // instead of silently clobbered.
    //
    // "Known to have been produced by pokie build" is read from the existing directory's own
    // src/generated/build-info.json — itself pokie build output — rather than assumed: its "files"
    // field lists exactly what that run generated, so a newer generator recognizes an older one's
    // output even if the generated file set has changed since.
    private assertSafeToRebuild(projectRoot: string): void {
        if (!fs.statSync(projectRoot).isDirectory()) {
            throw new Error(
                `"${projectRoot}" already exists and is not a directory. Choose a different --out directory or remove it first.`,
            );
        }

        // Unconditional, before any recognition check below: a known-recognized package (via
        // build-info.json's "files") is not enough to trust what's actually sitting at each public
        // path's own real location right now -- see assertTrustedPublicPaths.
        this.assertTrustedPublicPaths(projectRoot);

        const knownFiles = this.readKnownGeneratedFiles(projectRoot);
        const conflicting = GENERATED_PACKAGE_FILES.filter(
            (relativePath) => !knownFiles.includes(relativePath) && fs.existsSync(path.join(projectRoot, ...relativePath.split("/"))),
        );

        if (conflicting.length > 0) {
            throw new Error(
                `"${projectRoot}" already exists and contains file(s) "pokie build" did not generate: ${conflicting.join(", ")}. ` +
                    `Refusing to overwrite them — choose a different --out directory, remove the conflicting file(s), or point ` +
                    `--out at a directory previously produced by "pokie build" (recognized via its own src/generated/build-info.json).`,
            );
        }

        // A directory the prior build vouches for (via its own build-info.json) must still actually have
        // every one of those files on disk -- if any is now missing, the layout is an ambiguous partial
        // one publishRebuild has no safe way to reconcile (it commits each file independently, so it has
        // no way to tell "never existed" apart from "removed after the fact" for a path it's about to
        // replace). Fail closed here instead, before generate() does anything else.
        if (knownFiles.length > 0) {
            const missing = knownFiles.filter((relativePath) => !fs.existsSync(path.join(projectRoot, ...relativePath.split("/"))));
            if (missing.length > 0) {
                throw new Error(
                    `"${projectRoot}" is missing file(s) a previous "pokie build" generated: ${missing.join(", ")}. ` +
                        `Refusing to rebuild an incomplete package — restore the missing file(s), or remove "${projectRoot}" ` +
                        `and run "pokie build" fresh.`,
                );
            }
        }
    }

    // Validates each of the four fixed public paths (GENERATED_PACKAGE_FILES) before generate() trusts
    // their current type -- readPreviousBuildInfo reads through src/generated/build-info.json, and
    // publishRebuild's own rename-aside-then-restore rollback would otherwise happily rename a symlink
    // (or a directory) aside and back without ever noticing it wasn't the plain file this generator
    // itself always writes. Every public path that exists must be a plain regular file -- never a
    // symlink (which could point anywhere, including outside projectRoot entirely) or a directory --
    // and every ancestor directory between projectRoot and that path's own parent (only "src" and
    // "src/generated" nest more than one level deep) must itself be a real, non-symlink directory: lstat
    // on the leaf path alone never catches an attacker turning an *intermediate* component into a
    // symlink to an arbitrary external directory, since ordinary path resolution follows every
    // non-final component automatically. Every check here is lstat-based -- a symlink's target is never
    // dereferenced, read, copied, or written -- so a hostile target is inert no matter which check
    // rejects it.
    private assertTrustedPublicPaths(projectRoot: string): void {
        const remediation = `Refusing to rebuild "${projectRoot}" -- remove the conflicting file(s) (or all of "${projectRoot}") and run "pokie build" fresh.`;

        for (const relativePath of GENERATED_PACKAGE_FILES) {
            this.assertPlainAncestorDirectories(projectRoot, relativePath, remediation);

            const realPath = path.join(projectRoot, ...relativePath.split("/"));
            let stats: fs.Stats | undefined;
            try {
                stats = fs.lstatSync(realPath);
            } catch {
                stats = undefined;
            }

            if (stats !== undefined && !stats.isFile()) {
                throw new Error(
                    `"${realPath}" is a ${stats.isSymbolicLink() ? "symlink" : stats.isDirectory() ? "directory" : "special file"}, ` +
                        `not the plain file "pokie build" writes. ${remediation}`,
                );
            }
        }
    }

    // Walks every ancestor directory between projectRoot and relativePath's own parent (e.g. "src", then
    // "src/generated"), confirming each is a real (non-symlink) directory before relativePath's own leaf
    // is ever lstat'd or read/written through -- see assertTrustedPublicPaths for why lstat on the leaf
    // alone isn't enough. A missing ancestor is left alone here (nothing to reject yet); generate()'s own
    // GENERATED_PACKAGE_FILES conflict/missing-file checks handle that case.
    private assertPlainAncestorDirectories(projectRoot: string, relativePath: string, remediation: string): void {
        const segments = relativePath.split("/");

        let currentPath = projectRoot;
        for (let i = 0; i < segments.length - 1; i++) {
            currentPath = path.join(currentPath, segments[i]);
            if (!this.pathExists(currentPath)) {
                return;
            }

            const stats = fs.lstatSync(currentPath);
            if (!stats.isDirectory()) {
                throw new Error(
                    `"${currentPath}" is a ${stats.isSymbolicLink() ? "symlink" : "special file"}, ` +
                        `not the plain directory "pokie build" writes. ${remediation}`,
                );
            }
        }
    }

    // Returns the file list an existing directory's own build-info.json vouches for, or [] if there's
    // no build-info.json there, it doesn't parse, or it wasn't written by "pokie build" — in which case
    // every fixed output path found on disk is treated as a conflict.
    private readKnownGeneratedFiles(projectRoot: string): string[] {
        const previous = this.readPreviousBuildInfo(projectRoot);
        if (previous === undefined) {
            return [];
        }
        return Array.isArray(previous.files) ? previous.files : GENERATED_PACKAGE_FILES;
    }

    // Returns the existing directory's own build-info.json, or undefined if there's none there, it
    // doesn't parse, or it wasn't written by "pokie build". Feeds both readKnownGeneratedFiles (the
    // rebuild-safety check) and buildGameBuildInfo (the generatedAt reuse-on-no-op-rebuild check).
    private readPreviousBuildInfo(projectRoot: string): GameBuildInfo | undefined {
        const buildInfoPath = path.join(projectRoot, ...BUILD_INFO_RELATIVE_PATH.split("/"));
        if (!fs.existsSync(buildInfoPath)) {
            return undefined;
        }

        try {
            const parsed = JSON.parse(fs.readFileSync(buildInfoPath, "utf-8"));
            if (!parsed || parsed.generatedBy !== "pokie build") {
                return undefined;
            }
            return parsed as GameBuildInfo;
        } catch {
            return undefined;
        }
    }
}
