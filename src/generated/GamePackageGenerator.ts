import crypto from "crypto";
import fs from "fs";
import path from "path";
import {BUILT_PACKAGE_FILES} from "./buildGameBuildInfo.js";
import type {GameBlueprint} from "./GameBlueprint.js";
import type {GameBuildInfoReelStripGeneration} from "./GameBuildInfoReelStripGeneration.js";
import type {GamePackageGenerating} from "./GamePackageGenerating.js";
import type {GeneratedGamePackage} from "./GeneratedGamePackage.js";
import {materializeReelStrips} from "./materializeReelStrips.js";
import {renderBuiltGameModule} from "./renderBuiltGameModule.js";
import {renderBuiltPackageReadme} from "./renderBuiltPackageReadme.js";
import {resolveReelStripGeneration} from "./resolveReelStripGeneration.js";

const DEFAULT_DESCRIPTION = 'Generated by "pokie build" — a POKIE video slot game package.';

export class GamePackageGenerator implements GamePackageGenerating {
    private readonly pokieVersion: string;

    constructor(pokieVersion: string) {
        this.pokieVersion = pokieVersion;
    }

    // "blueprint" here is the blueprint exactly as authored/validated — including its per-reel
    // reelStripGeneration array, if any. "reelStripGeneration" is that array's *already resolved*
    // result (see resolveReelStripGeneration.ts) — normally BuildCommand runs resolution itself first
    // (so it can report per-reel diagnostics its own way) and passes the result straight through. A
    // caller that omits it entirely — e.g. calling this generator directly with an in-memory blueprint
    // — gets resolution run for it right here, failing the same way BuildCommand would have. The
    // actual runtime file (dist/index.js) gets a *materialized* copy (materializeReelStrips) with
    // reelStripGeneration resolved into a plain reelStrips array — the runtime module never depends on
    // the generation API.
    //
    // Writes the exact same canonical package shape "pokie create"/"pokie init" scaffold — package.json
    // (pokie.entry/main/exports all pointing at "dist/index.js"), README.md, and a single entry module
    // — with "dist/index.js" written directly rather than compiled from a separate "src/index.ts": this
    // generator's own source of truth is the GameBlueprint, not hand-written TypeScript, so there's
    // nothing to compile from and no separate compile step is needed for the output to be immediately
    // loadable. Nothing under the built package tracks where it came from (no embedded blueprint copy,
    // no build-info file, no "src/generated" nesting) — see BUILT_PACKAGE_FILES — so a later source
    // edit or rebuild never has to reconcile against, or is constrained by, whatever produced this
    // package originally.
    public generate(
        blueprint: GameBlueprint,
        cwd: string,
        outDir?: string,
        reelStripGeneration?: GameBuildInfoReelStripGeneration,
    ): GeneratedGamePackage {
        const id = blueprint.manifest.id;
        if (outDir === undefined && (id.includes("/") || id.includes("\\") || id === "." || id === "..")) {
            throw new Error(
                `"manifest.id" ("${id}") is not a valid directory name. Use a plain name, e.g. "sample-slot", or pass --out <dir>.`,
            );
        }

        const resolvedReelStripGeneration =
            reelStripGeneration !== undefined ? reelStripGeneration : this.resolveReelStripGenerationOrThrow(blueprint);

        const projectRoot = outDir !== undefined ? path.resolve(cwd, outDir) : path.join(cwd, id);
        this.assertMissingOrEmpty(projectRoot);

        // materializeReelStrips can throw (see its own fail-fast checks) — it runs before any
        // filesystem write below (including the staged directory this generator writes into first) so
        // a failure never creates or modifies anything, whether it's this call's own resolution or a
        // caller-supplied one.
        const materializedBlueprint = materializeReelStrips(blueprint, resolvedReelStripGeneration);

        const packageJson = {
            name: id,
            version: blueprint.manifest.version,
            description: blueprint.manifest.description ?? DEFAULT_DESCRIPTION,
            ...(blueprint.manifest.author ? {author: blueprint.manifest.author} : {}),
            keywords: ["pokie", "video-slot", "generated"],
            private: true,
            scripts: {
                start: "pokie dev .",
                server: "pokie serve .",
                client: "pokie client .",
            },
            dependencies: {
                pokie: `^${this.pokieVersion}`,
            },
            pokie: {
                entry: "./dist/index.js",
            },
        };

        this.publish(projectRoot, {
            "package.json": `${JSON.stringify(packageJson, null, 4)}\n`,
            "README.md": renderBuiltPackageReadme(blueprint.manifest),
            "dist/index.js": renderBuiltGameModule(materializedBlueprint, this.pokieVersion),
        });

        return {projectRoot, manifest: blueprint.manifest, createdFiles: [...BUILT_PACKAGE_FILES]};
    }

    // Stages every file into a fresh temp sibling directory first (touching nothing under projectRoot),
    // and only once every one of them has been written successfully is projectRoot itself ever touched
    // — a single atomic directory rename (assertMissingOrEmpty already guarantees projectRoot is either
    // absent or an empty directory, both of which a directory rename can safely replace), so a reader
    // can only ever observe projectRoot missing, or fully populated with every file — never a partial
    // write.
    private publish(projectRoot: string, contentsByRelativePath: Record<string, string>): void {
        const tempDir = `${projectRoot}.tmp-${crypto.randomBytes(6).toString("hex")}`;

        try {
            for (const [relativePath, contents] of Object.entries(contentsByRelativePath)) {
                const tempPath = path.join(tempDir, ...relativePath.split("/"));
                fs.mkdirSync(path.dirname(tempPath), {recursive: true});
                fs.writeFileSync(tempPath, contents);
            }
            fs.renameSync(tempDir, projectRoot);
        } catch (error) {
            this.removeBestEffort(tempDir);
            throw error;
        }
    }

    // Unlike the "pokie build" format this replaces, a rebuild into an already-populated directory is
    // never recognized/merged automatically — there is no tracked notion of "this directory is safe to
    // overwrite because a prior pokie build produced it" anymore (see this class's own doc comment).
    // Building again means removing the destination first, or pointing --out somewhere fresh.
    private assertMissingOrEmpty(projectRoot: string): void {
        if (!fs.existsSync(projectRoot)) {
            return;
        }
        if (!fs.statSync(projectRoot).isDirectory()) {
            throw new Error(
                `"${projectRoot}" already exists and is not a directory. Choose a different --out directory or remove it first.`,
            );
        }
        if (fs.readdirSync(projectRoot).length > 0) {
            throw new Error(
                `"${projectRoot}" already exists and is not empty. "pokie build" always writes a brand-new package into ` +
                    `a missing or empty directory — remove or empty "${projectRoot}" first, or build into a different ` +
                    `--out directory, and run "pokie build" again.`,
            );
        }
    }

    private removeBestEffort(targetPath: string): void {
        try {
            fs.rmSync(targetPath, {recursive: true, force: true});
        } catch {
            // best-effort only.
        }
    }

    // Runs resolveReelStripGeneration for a caller that didn't already do so (and pass its result in)
    // — mirrors what BuildCommand does with its own console.error reporting, but as a single thrown
    // error carrying every failed reel's diagnostics, since a direct caller has no per-reel reporting
    // of its own to hook into.
    private resolveReelStripGenerationOrThrow(blueprint: GameBlueprint): GameBuildInfoReelStripGeneration | undefined {
        const resolution = resolveReelStripGeneration(blueprint);
        if (resolution.success) {
            return resolution.reelStripGeneration;
        }

        const lines = resolution.reels
            .filter((reel) => !reel.success)
            .map((reel) => {
                const lastDiagnostic = reel.diagnostics[reel.diagnostics.length - 1];
                const violationLines = (lastDiagnostic?.violations ?? [])
                    .map((violation) => `      ${violation.constraintId}: ${violation.message}`)
                    .join("\n");
                return (
                    `  - reel ${reel.reelIndex} (seed ${reel.seed}): failed after ${reel.attemptsUsed} attempt(s)` +
                    (violationLines ? `\n${violationLines}` : "")
                );
            });

        throw new Error(`Blueprint "${blueprint.manifest.id}" could not generate its reel strips:\n${lines.join("\n")}`);
    }
}
