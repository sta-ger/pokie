import type {GameBlueprint} from "./GameBlueprint.js";
import {resolveBetModeCodegenWiring} from "./resolveBetModeCodegenWiring.js";

// Renders the built game module in each of the two forms GamePackageGenerator writes on every run:
// "dist/index.js" (plain CommonJS, immediately loadable with no separate compile step -- see
// renderBuiltGameModule below) and "src/index.ts" (the same module, typed and re-compilable via the
// package's own "tsconfig.json"/"npm run build", the exact same canonical shape "pokie create"/"pokie
// init" scaffold -- see renderBuiltGameModuleSource below). Both share every line of actual game-
// assembly logic, the "pokie" runtime binding, and the final export statement (computed once here);
// only a type-only import and a type annotation differ between them -- see the "typeImport"/
// "blueprintDeclaration" split below.
//
// Carries no static blueprint-hash/provenance header: a built package tracks nothing about where it
// came from (see GamePackageGenerator's own doc comment) beyond the embedded blueprint data itself.
// getConfigHash() (see PokieGame.getConfigHash's own doc comment) derives its result live from that
// already-embedded "blueprint" const (the *materialized* one -- see GamePackageGenerator's own
// materializeReelStrips call -- so a procedurally-generated blueprint's hash reflects its literal
// resolved reel strips, same as everything else this module embeds) via computeGameBlueprintHash,
// rather than a precomputed literal, so re-running "pokie build" on an unchanged blueprint still
// regenerates byte-identical files.
function renderBuiltGameModuleImpl(blueprint: GameBlueprint, pokieVersion: string, format: "cjs" | "ts"): string {
    const {manifest} = blueprint;
    const header = `// Game: ${manifest.name} (id: "${manifest.id}", version ${manifest.version})
// Generated by: pokie ${pokieVersion}`;

    // Absent winModel means today's default (line pays via VideoSlotConfig's own default win
    // calculator) — every existing blueprint keeps generating byte-identical output.
    const winModel = blueprint.winModel ?? {type: "lines" as const};
    const freeGames = blueprint.mechanics?.freeGames;
    const hasBetModes = (blueprint.betModes?.length ?? 0) > 0;
    const betModeWiring = resolveBetModeCodegenWiring(blueprint);

    const requireNames = [
        "computeGameBlueprintHash",
        "CustomLinesDefinitions",
        "SymbolsSequence",
        "VideoSlotConfig",
        "VideoSlotSession",
        "VideoSlotSessionSerializer",
    ];
    if (winModel.type === "ways" || winModel.type === "clusters") {
        requireNames.push("VideoSlotWinCalculator", "SelectedEvaluatorGroupWinAggregationPolicy");
        requireNames.push(winModel.type === "ways" ? "WaysWinCalculator" : "ClusterWinCalculator");
    }
    if (freeGames) {
        requireNames.push("VideoSlotWithFreeGamesConfig", "VideoSlotWithFreeGamesSession");
    }
    if (betModeWiring) {
        requireNames.push("BetModeDefinition", "BetModesConfig", "VideoSlotWithBetModesSession");
        if (betModeWiring.buyFeatureModes.length > 0) {
            requireNames.push("FreeGamesForcedFeatureEntryHandler", "PerModeForcedFeatureEntryHandler");
        }
    }
    requireNames.sort();

    // Built once here (not inline in createConfig/createSession) since both the config-wrapping and
    // the session/win-calculator construction below need to agree on it.
    let winCalculatorDeclaration = "";
    if (winModel.type === "ways") {
        winCalculatorDeclaration = `    const winCalculator = new VideoSlotWinCalculator(config, undefined, undefined, undefined, undefined, new WaysWinCalculator(config), {
        aggregationPolicy: new SelectedEvaluatorGroupWinAggregationPolicy("ways"),
    });
`;
    } else if (winModel.type === "clusters") {
        winCalculatorDeclaration = `    const winCalculator = new VideoSlotWinCalculator(config, undefined, undefined, new ClusterWinCalculator(config, ${winModel.minimumClusterSize ?? 5}), undefined, undefined, {
        aggregationPolicy: new SelectedEvaluatorGroupWinAggregationPolicy("cluster"),
    });
`;
    }
    const winCalculatorArgs = winModel.type === "lines" ? "" : ", undefined, winCalculator";
    const sessionClassName = freeGames ? "VideoSlotWithFreeGamesSession" : "VideoSlotSession";
    // Only introduce an intermediate "config" local when a winCalculator actually needs to reference
    // it — otherwise createSession() stays the exact one-liner it's always been.
    const sessionConstructionExpression = winCalculatorDeclaration
        ? `new ${sessionClassName}(config${winCalculatorArgs})`
        : `new ${sessionClassName}(createConfig())`;
    const configDeclaration = winCalculatorDeclaration ? `        const config = createConfig();\n${winCalculatorDeclaration}` : "";
    // Only wraps the session in VideoSlotWithBetModesSession when resolveBetModeCodegenWiring()
    // reports the whole betModes array validates cleanly under the explicit runtime-semantics contract
    // (see that function and gamepackage/BetMode.ts's own doc comment) -- costMultiplier alone (the
    // old, still-supported metadata-only shape) is never enough, and never guessed at, here.
    const forcedFeatureEntryHandlerDeclaration =
        betModeWiring && betModeWiring.buyFeatureModes.length > 0
            ? `        const forcedFeatureEntryHandler = new PerModeForcedFeatureEntryHandler(new Map([
${betModeWiring.buyFeatureModes
        .map(({id, forcedFreeGames}) => `            [${JSON.stringify(id)}, new FreeGamesForcedFeatureEntryHandler(${forcedFreeGames})],`)
        .join("\n")}
        ]));
`
            : "";
    const betModesWrapCode = betModeWiring
        ? `        const session = ${sessionConstructionExpression};
        const betModes = (blueprint.betModes || []).map((mode) => new BetModeDefinition(mode.id, {
            stakeMultiplier: mode.costMultiplier,
            forcesFeatureEntry: mode.runtimeType === "buyFeature",
            targetRtp: mode.targetRtp,
        }));
${forcedFeatureEntryHandlerDeclaration}        return new VideoSlotWithBetModesSession(session, new BetModesConfig(betModes, ${JSON.stringify(betModeWiring.defaultModeId)})${
    betModeWiring.buyFeatureModes.length > 0 ? ", forcedFeatureEntryHandler" : ""
});
`
        : `        return ${sessionConstructionExpression};
`;
    const createSessionBody = `${configDeclaration}${betModesWrapCode}`;

    const freeGamesWrapCode = freeGames
        ? `
    const freeGamesConfig = new VideoSlotWithFreeGamesConfig(config);
    const freeGamesMechanic = blueprint.mechanics && blueprint.mechanics.freeGames;
    if (freeGamesMechanic) {
        for (const [count, awarded] of Object.entries(freeGamesMechanic.awardsByCount)) {
            freeGamesConfig.setFreeGamesForScatters(freeGamesMechanic.scatterSymbol, Number(count), awarded);
        }
    }
`
        : "";
    const configReturnExpression = freeGames ? "freeGamesConfig" : "config";

    const betModesExport = hasBetModes
        ? `
    getBetModes() {
        return blueprint.betModes;
    },`
        : "";

    // Optional, feature-detected (see PokieGame.createExactEnumerationSession's own doc comment): a
    // plain, finite video-slot mechanic (no mechanics.freeGames -- the one currently-generated
    // stateful/non-reel-enumerable mechanic) always has a finite reel-stop space, so every generated
    // package for one opts in automatically, driving the exact same session/win-calculation runtime
    // createSession() does -- just with the caller-supplied deterministic combinationsGenerator in
    // place of the random one, never a second calculation path. A blueprint with mechanics.freeGames
    // simply omits this export -- weightedoutcome/generate fails closed rather than guessing at a
    // strategy for a mechanic whose outcome space isn't a finite set of reel-stop combinations.
    const exactWinCalculatorArgs = winModel.type === "lines" ? "" : ", winCalculator";
    // "combinationsGenerator" has no annotation to contextually infer from (this object literal is
    // never assigned to a typed PokieGame variable -- see the "typeImport"/"blueprintDeclaration" doc
    // comment above for why not) -- an explicit "unknown" annotation satisfies noImplicitAny for the
    // "ts" format without narrowing what a caller may pass; the "cjs" format stays annotation-free,
    // exactly as before.
    const combinationsGeneratorParam = format === "ts" ? "combinationsGenerator: unknown" : "combinationsGenerator";
    const exactEnumerationSessionExport = freeGames
        ? ""
        : `
    createExactEnumerationSession(${combinationsGeneratorParam}) {
        const config = createConfig();
${winCalculatorDeclaration}        return new VideoSlotSession(config, combinationsGenerator${exactWinCalculatorArgs});
    },`;

    // The only two lines that differ between "dist/index.js" (format "cjs") and "src/index.ts"
    // (format "ts"): a type-only "GameBlueprint" import (erased at compile time -- adds nothing to
    // the compiled output) and a matching type annotation on "blueprint" below, so that "npm run
    // build" recompiling src/index.ts type-checks cleanly under the package's own strict tsconfig.json
    // (blueprint's dynamically-keyed fields -- paytable, mechanics.freeGames.awardsByCount -- would
    // otherwise fail strict indexing checks against the object literal TypeScript infers for an
    // unannotated "const blueprint = {...}"). Everything else -- the "pokie" runtime binding itself
    // (still a plain require() destructure, not a typed import: every call it feeds stays untyped
    // "any" either way, so this never depends on "pokie"'s own exported method signatures) and the
    // final "module.exports" -- is byte-identical in both, so a real "npm run build" here reproduces
    // an equivalent, working dist/index.js.
    const typeImport = format === "ts" ? `import type {GameBlueprint} from "pokie";\n\n` : "";
    const blueprintDeclaration =
        format === "ts"
            ? `const blueprint: GameBlueprint = ${JSON.stringify(blueprint, null, 4)};`
            : `const blueprint = ${JSON.stringify(blueprint, null, 4)};`;

    return `// ============================================================================
// GENERATED FILE — do not hand-edit.
//
// Produced by "pokie build" from a GameBlueprint JSON config. Re-run "pokie build" (see this
// package's README.md) to regenerate this file after changing the blueprint; any manual edits here
// are overwritten on the next run.
//
${header}
// ============================================================================

${typeImport}// ---------------------------------------------------------------------------
// pokie runtime
// ---------------------------------------------------------------------------
const {
${requireNames.map((name) => `    ${name},`).join("\n")}
} = require("pokie");

// ---------------------------------------------------------------------------
// Blueprint data (embedded verbatim from the source GameBlueprint JSON config)
// ---------------------------------------------------------------------------
${blueprintDeclaration}

// ---------------------------------------------------------------------------
// VideoSlotConfig assembly
//
// Setter order matters here: setAvailableBets/setWildSymbols/setScatterSymbols must run before
// setAvailableSymbols, which rebuilds the paytable and (absent explicit reel strips) the default
// reel sequences from whatever wilds/scatters are set at that point. The paytable, paylines, and
// reel strips are set after setAvailableSymbols, since it would otherwise overwrite them. See
// VideoSlotConfig for the full contract.
// ---------------------------------------------------------------------------
function createConfig() {
    const config = new VideoSlotConfig();

    if (blueprint.availableBets) {
        config.setAvailableBets(blueprint.availableBets);
    }
    config.setReelsNumber(blueprint.reels);
    config.setReelsSymbolsNumber(blueprint.rows);
    config.setWildSymbols(blueprint.wilds || []);
    config.setScatterSymbols(blueprint.scatters || []);
    config.setAvailableSymbols(blueprint.symbols);

    const paytable = config.getPaytable();
    for (const symbolId of Object.keys(blueprint.paytable)) {
        const payouts = blueprint.paytable[symbolId];
        for (const times of Object.keys(payouts)) {
            paytable.setPayoutForSymbol(symbolId, Number(times), payouts[times]);
        }
    }

    if (blueprint.paylines) {
        const linesDefinitions = new CustomLinesDefinitions();
        blueprint.paylines.forEach((line, index) => linesDefinitions.setLineDefinition(String(index), line));
        config.setLinesDefinitions(linesDefinitions);
    }

    if (blueprint.reelStrips) {
        config.setSymbolsSequences(blueprint.reelStrips.map((strip) => new SymbolsSequence().fromArray(strip)));
    } else if (blueprint.symbolWeights) {
        const sequences = [];
        for (let i = 0; i < blueprint.reels; i++) {
            sequences.push(new SymbolsSequence().fromNumbersOfSymbols(blueprint.symbolWeights).shuffle());
        }
        config.setSymbolsSequences(sequences);
    }
${freeGamesWrapCode}
    return ${configReturnExpression};
}

// ---------------------------------------------------------------------------
// PokieGame contract (see docs/game-packages.md)
// ---------------------------------------------------------------------------
module.exports = {
    getManifest() {
        return blueprint.manifest;
    },
    createSession() {
${createSessionBody}    },
    getSessionSerializer() {
        return new VideoSlotSessionSerializer();
    },
    getConfigHash() {
        return computeGameBlueprintHash(blueprint);
    },${betModesExport}${exactEnumerationSessionExport}
};
`;
}

// "dist/index.js": plain CommonJS, immediately loadable with no separate compile step -- unlike
// "pokie create"/"pokie init" (which scaffold a TS project for a developer to hand-edit and compile
// themselves), this is the file every other "pokie" command actually loads.
export function renderBuiltGameModule(blueprint: GameBlueprint, pokieVersion: string): string {
    return renderBuiltGameModuleImpl(blueprint, pokieVersion, "cjs");
}

// "src/index.ts": the same module, typed and recompilable via the package's own "npm run build" --
// see renderBuiltGameModuleImpl's own doc comment for exactly what differs from renderBuiltGameModule.
export function renderBuiltGameModuleSource(blueprint: GameBlueprint, pokieVersion: string): string {
    return renderBuiltGameModuleImpl(blueprint, pokieVersion, "ts");
}
