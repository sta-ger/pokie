// Development-only: wat2wasm (WABT) must be on PATH. No compiler is needed at runtime.
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
const source = fileURLToPath(new URL('./shared-math.wat', import.meta.url));
const output = `${source}.tmp`;
try {
    execFileSync('wat2wasm', [source, '-o', output]);
    const bytes = fs.readFileSync(output);
    fs.writeFileSync(new URL('./internal/SharedMathKernel.ts', import.meta.url), `// Generated by src/wasm/math/generate-kernel.mjs from shared-math.wat.\nexport const SHARED_MATH_KERNEL = new Uint8Array([\n${Array.from({length: Math.ceil(bytes.length / 32)}, (_, i) => '    ' + [...bytes.subarray(i * 32, (i + 1) * 32)].join(', ') + ',').join('\n')}\n]);\n`);
} finally {
    fs.rmSync(output, {force: true});
}
